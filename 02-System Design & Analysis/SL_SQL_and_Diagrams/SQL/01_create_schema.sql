-- Fresh schema; rerunnable CREATE IF NOT EXISTS. Does not migrate existing tables.
-- No destructive statements. Required execution order: 01 -> 02 -> 03 -> 04.
-- EDA-selected category labels are not provided. Do not insert fake labels.

CREATE TABLE IF NOT EXISTS supported_category (
  category_code VARCHAR(64) PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_supported_category_01 CHECK (length(trim(category_code)) > 0),
  CONSTRAINT ck_supported_category_02 CHECK (length(trim(display_name)) > 0)
);

CREATE TABLE IF NOT EXISTS product_listing (
  listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  image_ref TEXT NOT NULL,
  image_sha256 CHAR(64),
  image_origin VARCHAR(40) NOT NULL DEFAULT 'fashion_product_images_small',
  dataset_product_id VARCHAR(80),
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  seller_category VARCHAR(120) NOT NULL,
  text_origin VARCHAR(32) NOT NULL DEFAULT 'seller_input',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_product_listing_01 CHECK (length(trim(image_ref)) > 0),
  CONSTRAINT ck_product_listing_02 CHECK (image_sha256 IS NULL OR length(image_sha256) = 64),
  CONSTRAINT ck_product_listing_03 CHECK (image_origin = 'fashion_product_images_small'),
  CONSTRAINT ck_product_listing_04 CHECK (text_origin IN ('seller_input','manual_demo','synthetic_evaluation')),
  CONSTRAINT ck_product_listing_05 CHECK (seller_category IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS analysis_run (
  analysis_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'running',
  queue_state VARCHAR(24),
  inconsistency_level VARCHAR(8),
  quality_score NUMERIC(5,2),
  image_width_px INTEGER,
  image_height_px INTEGER,
  is_blurred BOOLEAN,
  brightness_status VARCHAR(12),
  cv_model_version VARCHAR(120),
  nlp_lexicon_version VARCHAR(120),
  ruleset_version VARCHAR(120),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ,
  CONSTRAINT fk_analysis_run_listing_id FOREIGN KEY (listing_id) REFERENCES product_listing(listing_id) ON DELETE RESTRICT,
  CONSTRAINT ck_analysis_run_01 CHECK (status IN ('running','completed','partial','failed')),
  CONSTRAINT ck_analysis_run_02 CHECK (queue_state IS NULL OR queue_state IN ('ready_to_publish','needs_review','critical_mismatch')),
  CONSTRAINT ck_analysis_run_03 CHECK (inconsistency_level IS NULL OR inconsistency_level IN ('low','medium','high')),
  CONSTRAINT ck_analysis_run_04 CHECK (quality_score IS NULL OR (quality_score >= 0 AND quality_score <= 100)),
  CONSTRAINT ck_analysis_run_05 CHECK (image_width_px IS NULL OR image_width_px > 0),
  CONSTRAINT ck_analysis_run_06 CHECK (image_height_px IS NULL OR image_height_px > 0),
  CONSTRAINT ck_analysis_run_07 CHECK (brightness_status IS NULL OR brightness_status IN ('dark','normal','bright')),
  CONSTRAINT ck_analysis_run_08 CHECK ((status = 'running' AND queue_state IS NULL) OR (status = 'failed' AND queue_state IS NULL) OR (status = 'completed' AND queue_state IS NOT NULL) OR (status = 'partial' AND queue_state = 'needs_review')),
  CONSTRAINT ck_analysis_run_09 CHECK (completed_at IS NULL OR completed_at >= created_at)
);

CREATE TABLE IF NOT EXISTS visual_prediction (
  prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_run_id BIGINT NOT NULL,
  attribute VARCHAR(16) NOT NULL,
  model_source VARCHAR(20) NOT NULL,
  prediction_state VARCHAR(16) NOT NULL,
  predicted_category_code VARCHAR(64),
  predicted_color VARCHAR(80),
  confidence NUMERIC(5,4),
  is_selected BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_visual_prediction_1 UNIQUE (analysis_run_id, attribute, model_source),
  CONSTRAINT fk_visual_prediction_analysis_run_id FOREIGN KEY (analysis_run_id) REFERENCES analysis_run(analysis_run_id) ON DELETE CASCADE,
  CONSTRAINT fk_visual_prediction_predicted_category_code FOREIGN KEY (predicted_category_code) REFERENCES supported_category(category_code) ON DELETE RESTRICT,
  CONSTRAINT ck_visual_prediction_01 CHECK (attribute IN ('product_type','color')),
  CONSTRAINT ck_visual_prediction_02 CHECK (model_source IN ('primary_cv','clip_zero_shot','dominant_color')),
  CONSTRAINT ck_visual_prediction_03 CHECK (prediction_state IN ('predicted','uncertain','unavailable')),
  CONSTRAINT ck_visual_prediction_04 CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
  CONSTRAINT ck_visual_prediction_05 CHECK ((attribute = 'product_type' AND predicted_color IS NULL) OR (attribute = 'color' AND predicted_category_code IS NULL)),
  CONSTRAINT ck_visual_prediction_06 CHECK ((prediction_state = 'predicted' AND confidence IS NOT NULL AND ((attribute = 'product_type' AND predicted_category_code IS NOT NULL) OR (attribute = 'color' AND predicted_color IS NOT NULL))) OR (prediction_state <> 'predicted' AND predicted_category_code IS NULL AND predicted_color IS NULL)),
  CONSTRAINT ck_visual_prediction_07 CHECK (NOT is_selected OR prediction_state = 'predicted'),
  CONSTRAINT ck_visual_prediction_08 CHECK (model_source <> 'dominant_color' OR attribute = 'color')
);

CREATE TABLE IF NOT EXISTS text_claim (
  claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_run_id BIGINT NOT NULL,
  attribute VARCHAR(16) NOT NULL,
  source_field VARCHAR(16) NOT NULL,
  matched_text TEXT NOT NULL,
  canonical_value VARCHAR(120) NOT NULL,
  script_route VARCHAR(8) NOT NULL,
  CONSTRAINT fk_text_claim_analysis_run_id FOREIGN KEY (analysis_run_id) REFERENCES analysis_run(analysis_run_id) ON DELETE CASCADE,
  CONSTRAINT ck_text_claim_01 CHECK (attribute IN ('product_type','color')),
  CONSTRAINT ck_text_claim_02 CHECK (source_field IN ('title','description')),
  CONSTRAINT ck_text_claim_03 CHECK (script_route IN ('english','arabic')),
  CONSTRAINT ck_text_claim_04 CHECK (length(trim(matched_text)) > 0),
  CONSTRAINT ck_text_claim_05 CHECK (length(trim(canonical_value)) > 0)
);

CREATE TABLE IF NOT EXISTS analysis_finding (
  finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_run_id BIGINT NOT NULL,
  reason_code VARCHAR(32) NOT NULL,
  attribute_scope VARCHAR(16) NOT NULL,
  severity VARCHAR(8),
  confidence NUMERIC(5,4),
  visual_value VARCHAR(120),
  claimed_value VARCHAR(120),
  explanation TEXT NOT NULL,
  CONSTRAINT uq_analysis_finding_1 UNIQUE (analysis_run_id, reason_code, attribute_scope),
  CONSTRAINT fk_analysis_finding_analysis_run_id FOREIGN KEY (analysis_run_id) REFERENCES analysis_run(analysis_run_id) ON DELETE CASCADE,
  CONSTRAINT ck_analysis_finding_01 CHECK (reason_code IN ('TYPE_MISMATCH','COLOR_MISMATCH','LOW_CONFIDENCE','IMAGE_BLUR','MISSING_ATTRIBUTE','UNSUPPORTED_CATEGORY')),
  CONSTRAINT ck_analysis_finding_02 CHECK (attribute_scope IN ('product_type','color','image','listing')),
  CONSTRAINT ck_analysis_finding_03 CHECK (severity IS NULL OR severity IN ('critical','major','minor')),
  CONSTRAINT ck_analysis_finding_04 CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
  CONSTRAINT ck_analysis_finding_05 CHECK (length(trim(explanation)) > 0),
  CONSTRAINT ck_analysis_finding_06 CHECK ((reason_code = 'TYPE_MISMATCH' AND attribute_scope = 'product_type' AND severity IN ('critical','major')) OR (reason_code = 'COLOR_MISMATCH' AND attribute_scope = 'color' AND severity IN ('major','minor')) OR (reason_code = 'IMAGE_BLUR' AND attribute_scope = 'image' AND severity IS NULL) OR (reason_code = 'UNSUPPORTED_CATEGORY' AND attribute_scope = 'listing' AND severity IS NULL) OR (reason_code = 'LOW_CONFIDENCE' AND attribute_scope IN ('product_type','color','listing') AND severity IS NULL) OR (reason_code = 'MISSING_ATTRIBUTE' AND attribute_scope IN ('product_type','color') AND severity IS NULL))
);

CREATE TABLE IF NOT EXISTS suggested_correction (
  suggestion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  analysis_run_id BIGINT NOT NULL,
  suggested_title TEXT NOT NULL,
  suggested_description TEXT NOT NULL,
  change_explanation TEXT NOT NULL,
  CONSTRAINT uq_suggested_correction_1 UNIQUE (analysis_run_id),
  CONSTRAINT fk_suggested_correction_analysis_run_id FOREIGN KEY (analysis_run_id) REFERENCES analysis_run(analysis_run_id) ON DELETE CASCADE,
  CONSTRAINT ck_suggested_correction_01 CHECK (length(trim(change_explanation)) > 0)
);

CREATE TABLE IF NOT EXISTS seller_decision (
  decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  suggestion_id BIGINT NOT NULL,
  decision VARCHAR(8) NOT NULL,
  final_title TEXT,
  final_description TEXT,
  decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_seller_decision_1 UNIQUE (suggestion_id),
  CONSTRAINT fk_seller_decision_suggestion_id FOREIGN KEY (suggestion_id) REFERENCES suggested_correction(suggestion_id) ON DELETE RESTRICT,
  CONSTRAINT ck_seller_decision_01 CHECK (decision IN ('accept','edit','ignore')),
  CONSTRAINT ck_seller_decision_02 CHECK ((decision = 'edit' AND final_title IS NOT NULL AND final_description IS NOT NULL) OR (decision IN ('accept','ignore') AND final_title IS NULL AND final_description IS NULL))
);
